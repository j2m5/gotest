import assert from 'node:assert/strict'

export async function assertNPCs({ session, command, evaluate, waitFor, click, clickText, checkLayout, nextEvent, characterId, planetId, otherPlanetId, locations, homeCode }) {
  const first = locations[0], second = locations[1]
  const cards = () => evaluate(session, `[...document.querySelectorAll('.npc-list > li')].map(item => Number(item.dataset.npcId))`)
  await clickText(session, 'Локации планеты')
  await waitFor(session, `document.querySelectorAll('.location-list > li').length === 10`, 'NPC location list')
  await click(session, `[data-location-id="${first.id}"] .ui-button`)
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4`, 'four shared NPCs')
  const initialIDs = await cards()
  const fromAPI = await evaluate(session, `fetch('/api/npcs?character_id=${characterId}&location_id=${first.id}').then(r=>r.json())`)
  assert.deepEqual(initialIDs, fromAPI.npcs.map(npc => npc.id))
  assert.deepEqual(fromAPI.npcs.map(npc => npc.rank), ['normal', 'normal', 'strong', 'elite'])
  assert.equal(await evaluate(session, `[...document.querySelectorAll('.npc-section button')].some(button=>button.textContent.includes('Атаковать'))`), false)
  await checkLayout(session, 'npc-list')
  await clickText(session, 'Обновить список')
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4`, 'NPC refresh')
  assert.deepEqual(await cards(), initialIDs, 'Refresh never creates new instances')
  await command('Page.reload', {}, session)
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4`, 'NPC reload')
  assert.deepEqual(await cards(), initialIDs)
  await command('Network.setExtraHTTPHeaders', { headers: { 'X-Browser-Test-NPC-Failure': '1' } }, session)
  await clickText(session, 'Обновить список')
  await waitFor(session, `!!document.querySelector('.npc-section [role="alert"]')`, 'NPC failure')
  assert.deepEqual(await cards(), [], 'Failed read hides stale NPCs')
  await command('Network.setExtraHTTPHeaders', { headers: {} }, session)
  await clickText(session, 'Повторить')
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4`, 'NPC retry')

  // Hold an actual old-location response while the user moves to another area.
  const response = nextEvent(session, 'Fetch.requestPaused')
  await command('Fetch.enable', { patterns: [{ urlPattern: `*/api/npcs*location_id=${first.id}`, requestStage: 'Response' }] }, session)
  await clickText(session, 'Обновить список')
  const held = await response
  await clickText(session, 'Локации планеты')
  await waitFor(session, `document.querySelectorAll('.location-list > li').length === 10`, 'leave held NPC response')
  await click(session, `[data-location-id="${second.id}"] button`)
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4 && !!document.querySelector('[data-current-location-id="${second.id}"]')`, 'NPCs at new location')
  const secondIDs = await cards()
  assert(secondIDs.every(id => !initialIDs.includes(id)), 'Other location has different shared instances')
  await command('Fetch.continueResponse', { requestId: held.requestId }, session).catch(error => { if (!/Invalid InterceptionId|Invalid requestId|not found/i.test(error.message)) throw error })
  await command('Fetch.disable', {}, session)
  await evaluate(session, 'new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve(true))))')
  assert.deepEqual(await cards(), secondIDs, 'Late response does not repopulate the old area')

  const travel = await evaluate(session, `fetch('/api/world/travel',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({character_id:${characterId},planet_id:${otherPlanetId},from_location_id:${second.id}})}).then(r=>r.status)`)
  assert.equal(travel, 200)
  await clickText(session, 'Обновить список')
  await waitFor(session, `document.querySelector('main [role="alert"]')?.textContent.includes('текущей планете')`, 'NPC conflict refreshes parent position')
  assert.deepEqual(await cards(), [])
  await clickText(session, 'К галактике')
  await waitFor(session, `!!document.querySelector('.world-position')`, 'galaxy on additional world')
  const nextWorldCode = homeCode === 'coruscant' ? 'tython' : 'korriban'
  const nextCatalog = await evaluate(session, `fetch('/api/world/locations?character_id=${characterId}&planet_id=${otherPlanetId}').then(r=>r.json())`)
  assert.equal(nextCatalog.locations.length, 10)
  await clickText(session, 'Локации планеты')
  await waitFor(session, `document.querySelectorAll('.location-list > li').length === 10`, 'ten additional world areas')
  await checkLayout(session, `${nextWorldCode}-locations`)
  await clickText(session, 'Открыть')
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4`, 'additional world NPCs')
  const nextIDs = await cards()
  assert(nextIDs.every(id => !initialIDs.includes(id) && !secondIDs.includes(id)), 'New world has its own NPC instances')
  await command('Network.setExtraHTTPHeaders', { headers: { 'X-Browser-Test-NPC-Empty': '1' } }, session)
  await clickText(session, 'Обновить список')
  await waitFor(session, `document.querySelector('.npc-section')?.textContent.includes('Пока нет противников')`, 'empty NPC pool')
  assert.deepEqual(await cards(), [], 'Empty response hides previously populated list')
  await command('Network.setExtraHTTPHeaders', { headers: {} }, session)
  await clickText(session, 'Обновить список')
  await waitFor(session, `document.querySelectorAll('.npc-list > li').length === 4`, 'populated list restored')
  assert.deepEqual(await cards(), nextIDs)

  const finalArea = nextCatalog.locations[9]
  assert.equal(finalArea.recommended_level, 46)
  await clickText(session, 'Локации планеты')
  await waitFor(session, `document.querySelectorAll('.location-list > li').length === 10`, 'additional world location list')
  await click(session, `[data-location-id="${finalArea.id}"] button`)
  await waitFor(session, `!!document.querySelector('[data-current-location-id="${finalArea.id}"]') && document.querySelectorAll('.npc-list > li').length === 4`, 'enter final additional world area')
  const finalIDs = await cards()
  assert(finalIDs.every(id => !nextIDs.includes(id)), 'Final area has different shared NPCs')
  assert.deepEqual(await evaluate(session, `[...document.querySelectorAll('.npc-meta span:first-child')].map(item=>item.textContent)`), ['Уровень 46', 'Уровень 46', 'Уровень 48', 'Уровень 50'])
  await command('Page.reload', {}, session)
  await waitFor(session, `!!document.querySelector('[data-current-location-id="${finalArea.id}"]') && document.querySelectorAll('.npc-list > li').length === 4`, 'additional world position persists')
  assert.deepEqual(await cards(), finalIDs)
  await checkLayout(session, `${nextWorldCode}-npcs`)
  await clickText(session, 'К галактике')
  await waitFor(session, `!!document.querySelector('.world-position')`, 'return to galaxy after NPC tests')
  await click(session, `[data-planet-code="${homeCode}"] button`)
  await waitFor(session, `document.querySelector('.world-position')?.dataset.planetCode === '${homeCode}' && !document.querySelector('[aria-busy="true"]')`, 'return home after NPC tests')
}
